"""Built-in, locally synthesized background-music library.

Tracks live under ``workbench/assets/music`` with a small ``music.json``
manifest.  Everything is generated by ``_generate.py`` from pure oscillators,
so there are no third-party samples and no licence obligations beyond the
project's own terms.
"""
from __future__ import annotations

import hashlib
import json
import stat
from pathlib import Path

MUSIC_DIR = Path(__file__).resolve().parent / "assets" / "music"
MANIFEST = MUSIC_DIR / "music.json"
AUDIO_SUFFIXES = {".mp3", ".wav", ".m4a", ".aac", ".flac"}


class MusicError(ValueError):
    pass


def _safe_file(path: Path) -> bool:
    try:
        st = path.lstat()
    except OSError:
        return False
    if stat.S_ISLNK(st.st_mode) or getattr(st, "st_file_attributes", 0) & 0x400:
        return False
    return stat.S_ISREG(st.st_mode) and path.suffix.lower() in AUDIO_SUFFIXES


def _load() -> list[dict]:
    try:
        raw = json.loads(MANIFEST.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    rows = raw.get("tracks") if isinstance(raw, dict) else None
    if not isinstance(rows, list):
        return []
    out: list[dict] = []
    for row in rows:
        if not isinstance(row, dict):
            continue
        name = str(row.get("file") or "").strip()
        if not name or "/" in name or "\\" in name or name.startswith("."):
            continue
        path = (MUSIC_DIR / name).resolve()
        try:
            path.relative_to(MUSIC_DIR.resolve())
        except ValueError:
            continue
        if not _safe_file(path):
            continue
        title = str(row.get("title") or path.stem).strip()[:60]
        mood = str(row.get("mood") or "其他").strip()[:12]
        ident = hashlib.sha1(name.encode("utf-8")).hexdigest()[:12]
        out.append({
            "id": ident,
            "title": title,
            "mood": mood,
            "bpm": int(row.get("bpm") or 0),
            "duration": float(row.get("duration") or 0),
            "license": str(row.get("license") or "本机合成，可商用")[:80],
            "file": name,
            "path": str(path),
        })
    return out


def list_tracks() -> list[dict]:
    return _load()


def find(music_id: object) -> dict:
    if not isinstance(music_id, str) or not music_id:
        raise MusicError("曲目不存在")
    for row in _load():
        if row["id"] == music_id:
            return row
    raise MusicError("曲目不存在或文件已被移除")


def resolve(music_id: object) -> Path:
    row = find(music_id)
    path = (MUSIC_DIR / row["file"]).resolve()
    if not _safe_file(path):
        raise MusicError("曲目文件不可用")
    return path
